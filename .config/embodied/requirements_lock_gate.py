# Fail when a compiled requirements lock disagrees with the inputs its header names.
# A lock is a tracked *.txt file whose header is the one `uv pip compile` or
# `pip-compile` writes; its header command names the *.in inputs it was compiled from.
# Every exact pin in an input must equal the lock's pin, every lock entry annotated
# `-r <input>` must still be pinned there, and every tracked *.in file must be named by
# a lock header. Renovate's pip_requirements manager bumped the lock alone and left the
# input pin stale (pull requests 16 and 20, 2026-11-19); this gate turns that into a
# failing check offline, before the pull request reaches CI.
# The header must open the file, as Renovate's pip-compile manager also requires. A lock
# whose header follows a prelude (the Praetor-managed REUSE lock, compiled from an input
# this repository does not track) is named as not checked on every run.

import os
import re
import shlex
import shutil
import subprocess
import sys

MAX_FILE_BYTES = 4 * 1024 * 1024
MAX_HEADER_LINES = 16
MAX_TRACKED_PATHS = 100_000
LOCK_MARKERS = (
    re.compile(r"^# This file was autogenerated by uv via the following command:$"),
    re.compile(r"^# This file is autogenerated by pip-compile with Python \S+$"),
)
COMMAND_LINE = re.compile(r"^# {4}(?P<command>\S+)(?P<arguments> .*)?$")
PIN = re.compile(
    r"^(?P<name>[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)(?:\[[^\]]*\])?"
    r"\s*==\s*(?P<version>[A-Za-z0-9][A-Za-z0-9.!+_-]*)\s*(?:;.*)?$"
)
VIA_INPUT = re.compile(r"(?:^|\s)-r\s+(?P<source>\S+)$")
INPUT_COMMENT = re.compile(r"(?:^|\s)#.*$")
NUMERIC_RELEASE = re.compile(r"^\d+(?:\.\d+)*$")
# Header options the gate accepts: flags that take no separate argument, and any
# --name=value option (Renovate's pip-compile manager also requires the = form).
# Anything else might consume the next word, so it fails closed.
BARE_FLAGS = frozenset(("--universal", "--generate-hashes", "--allow-unsafe", "--strip-extras",
                        "--no-emit-index-url", "--no-header", "--no-annotate"))
OPTION_WITH_VALUE = re.compile(r"^--[a-z][a-z0-9-]*=")


def canonical_name(name):
    """Return the PEP 503 normalised form of a distribution name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def canonical_version(version):
    """Return version with trailing zero release parts dropped when it is a plain release."""
    if not NUMERIC_RELEASE.match(version):
        return version
    parts = version.split(".")
    for _ in range(len(parts) - 1):
        if parts[-1] != "0":
            break
        parts.pop()
    return ".".join(parts)


def read_text(top, path):
    """Read tracked file path under top as UTF-8 text.

    Return (text, None) on success, or (None, error) if it is missing, too large or not UTF-8.
    """
    full = os.path.join(top, path)
    try:
        size = os.path.getsize(full)
        if size > MAX_FILE_BYTES:
            return None, f"{path}: {size} bytes exceeds the {MAX_FILE_BYTES} byte limit"
        with open(full, "rb") as handle:
            data = handle.read(MAX_FILE_BYTES + 1)
    except OSError as error:
        return None, f"{path}: cannot read: {error}"
    try:
        return data.decode("utf-8"), None
    except UnicodeDecodeError as error:
        return None, f"{path}: not UTF-8: {error}"


def lock_header(text):
    """Classify text by its lock header; return (kind, command).

    kind is "lock" when the leading comment block carries a uv or pip-compile marker
    (command is its compile line, or None if absent), "unchecked" when a marker appears
    only after a prelude, and None when text is no lock.
    """
    lines = text.splitlines()[:MAX_HEADER_LINES]
    header = []
    for line in lines:
        if not line.startswith("#"):
            break
        header.append(line)
    if not any(marker.match(line) for line in header for marker in LOCK_MARKERS):
        later = any(marker.match(line) for line in lines for marker in LOCK_MARKERS)
        return ("unchecked" if later else None), None
    for line in header:
        match = COMMAND_LINE.match(line)
        if match and match.group("command") in ("uv", "pip-compile"):
            return "lock", match.group("command") + (match.group("arguments") or "")
    return "lock", None


def command_inputs(path, command):
    """Split lock path's header command into (inputs, error), inputs relative to the repository top.

    Inputs and --output-file resolve against the lock's directory, where the header says to
    run the command; --output-file must name the lock itself.
    """
    if command is None:
        return None, f"{path}: lock header carries no compile command line"
    try:
        argv = shlex.split(command)
    except ValueError as error:
        return None, f"{path}: header command does not parse: {error}"
    if argv[:3] == ["uv", "pip", "compile"]:
        arguments = argv[3:]
    elif argv[:1] == ["pip-compile"]:
        arguments = argv[1:]
    else:
        return None, f"{path}: header command is neither uv pip compile nor pip-compile"
    base = os.path.dirname(path)
    inputs, output = [], None
    for argument in arguments:
        if argument.startswith("--output-file="):
            output = os.path.normpath(os.path.join(base, argument.split("=", 1)[1]))
        elif not argument.startswith("-"):
            inputs.append(os.path.normpath(os.path.join(base, argument)))
        elif not (argument in BARE_FLAGS or OPTION_WITH_VALUE.match(argument)):
            return None, f"{path}: header option {argument} is not in this gate's allow-list"
    if output != os.path.normpath(path):
        return None, f"{path}: header --output-file names {output}, not this file"
    if not inputs:
        return None, f"{path}: header command names no input file"
    return inputs, None


def input_pins(path, text):
    """Parse the exact pins of input file path from text.

    Return ({name: (written pin, version)}, errors); any line other than a comment or an
    exact `name==version` pin is an error, so the gate never skips a requirement.
    """
    pins, errors = {}, []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = INPUT_COMMENT.sub("", raw).strip()
        if not line:
            continue
        match = PIN.match(line)
        if not match:
            errors.append(f"{path}:{number}: not an exact name==version pin: {raw.strip()}")
            continue
        name = canonical_name(match.group("name"))
        if name in pins:
            errors.append(f"{path}:{number}: {match.group('name')} is pinned twice")
            continue
        written = f"{match.group('name')}=={match.group('version')}"
        pins[name] = (written, canonical_version(match.group("version")))
    return pins, errors


def lock_entries(path, text):
    """Parse lock file path from text into ({name: {version: written}}, {name: inputs}, errors).

    Column-0 lines must be comments or pins; indented lines must be hashes or comments,
    whose `-r <input>` annotations record which inputs asked for the entry above them.
    """
    versions, via, errors, current = {}, {}, [], None
    for number, raw in enumerate(text.splitlines(), start=1):
        stripped = raw.strip()
        if not stripped or raw.startswith("#"):
            continue
        if raw[0].isspace():
            if stripped.startswith("#") and current:
                found = VIA_INPUT.search(stripped.lstrip("# "))
                if found:
                    via.setdefault(current, set()).add(found.group("source"))
            elif not (stripped.startswith("--hash=") or stripped.startswith("#")):
                errors.append(f"{path}:{number}: unexpected indented line: {stripped}")
            continue
        match = PIN.match(stripped.rstrip("\\").strip())
        if not match:
            errors.append(f"{path}:{number}: not a name==version lock entry: {stripped}")
            current = None
            continue
        current = canonical_name(match.group("name"))
        version = match.group("version")
        versions.setdefault(current, {})[canonical_version(version)] = version
    return versions, via, errors


def compare_pair(lock, source, pins, versions, via, written):
    """Return drift errors between input source's pins and lock's entries.

    written is the input path as the header spells it, which `-r` annotations repeat.
    """
    errors = []
    for name, (label, version) in sorted(pins.items()):
        locked = versions.get(name)
        if not locked:
            errors.append(f"{source}: {label} has no entry in {lock}")
        elif set(locked) != {version}:
            found = ", ".join(sorted(locked.values()))
            errors.append(f"{source}: {label} but {lock} pins {found}")
    for name, sources in sorted(via.items()):
        if written in sources and name not in pins:
            errors.append(f"{lock}: {name} is annotated -r {written}, but {source} no longer pins it")
    return errors


def check_lock(top, lock, text, tracked):
    """Check one lock against every input its header names.

    Return (inputs_covered, errors).
    """
    inputs, error = command_inputs(lock, lock_header(text)[1])
    if error:
        return [], [error]
    versions, via, errors = lock_entries(lock, text)
    base = os.path.dirname(lock)
    for source in inputs:
        if not source.endswith(".in"):
            errors.append(f"{lock}: input {source} is not a *.in file; this gate checks only *.in inputs")
            continue
        if source not in tracked:
            errors.append(f"{lock}: input {source} is not a tracked file")
            continue
        source_text, error = read_text(top, source)
        if error:
            errors.append(error)
            continue
        pins, pin_errors = input_pins(source, source_text)
        errors.extend(pin_errors)
        written = os.path.relpath(source, base or ".")
        errors.extend(compare_pair(lock, source, pins, versions, via, written))
    return inputs, errors


def tracked_paths(git, top):
    """List tracked *.txt and *.in paths in top with git.

    Return (paths, None) on success, or (None, error) if git fails or lists too many paths.
    """
    try:
        result = subprocess.run(
            [git, "ls-files", "-z", "--", "*.txt", "*.in"],
            cwd=top, capture_output=True, timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as error:
        return None, f"git ls-files failed: {error}"
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        return None, f"git ls-files failed (exit {result.returncode}): {detail}"
    paths = [os.fsdecode(raw) for raw in result.stdout.split(b"\0") if raw]
    if len(paths) > MAX_TRACKED_PATHS:
        return None, f"git ls-files listed {len(paths)} paths, above the {MAX_TRACKED_PATHS} limit"
    return paths, None


def repository_top(git):
    """Return (top, None) for the current checkout, or (None, error) if git cannot name it."""
    try:
        result = subprocess.run(
            [git, "rev-parse", "--show-toplevel"], capture_output=True, timeout=30,
        )
    except (OSError, subprocess.SubprocessError) as error:
        return None, f"git rev-parse failed: {error}"
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        return None, f"git rev-parse failed (exit {result.returncode}): {detail}"
    return os.fsdecode(result.stdout.strip()), None


def check_repository(top, paths):
    """Check every tracked lock in top and every tracked input.

    Return (checked, unchecked, errors): lock paths checked, lock paths whose header
    follows a prelude, and drift or parse errors.
    """
    tracked, covered, checked, unchecked, errors = set(paths), set(), [], [], []
    for path in sorted(p for p in paths if p.endswith(".txt")):
        text, error = read_text(top, path)
        if error:
            errors.append(error)
            continue
        kind, _ = lock_header(text)
        if kind == "unchecked":
            unchecked.append(path)
        if kind != "lock":
            continue
        checked.append(path)
        inputs, lock_errors = check_lock(top, path, text, tracked)
        covered.update(inputs)
        errors.extend(lock_errors)
    for path in sorted(p for p in paths if p.endswith(".in")):
        if path not in covered:
            errors.append(f"{path}: no tracked lock names this input in its header")
    return checked, unchecked, errors


def main():
    """Check this checkout's compiled requirements locks against their inputs.

    Print drift to stderr and return 1, or print a summary and return 0 when all agree.
    """
    git = shutil.which("git")
    if git is None:
        print("requirements_lock_gate: git not found on PATH", file=sys.stderr)
        return 1
    top, error = repository_top(git)
    if error is None:
        paths, error = tracked_paths(git, top)
    if error:
        print(f"requirements_lock_gate: {error}", file=sys.stderr)
        return 1
    checked, unchecked, errors = check_repository(top, paths)
    for path in unchecked:
        print(f"requirements_lock_gate: not checked: {path}: lock header does not open the file")
    for line in errors:
        print(f"requirements_lock_gate: {line}", file=sys.stderr)
    if errors:
        print(
            "requirements_lock_gate: change the pin in the input, then regenerate the lock "
            "with the command in its header",
            file=sys.stderr,
        )
        return 1
    print(f"requirements_lock_gate: pins agree with their inputs: {', '.join(checked) or 'no locks'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
