# Fail when a compiled requirements lock disagrees with the inputs its header names.
# A lock is a tracked *.txt file whose header is the one `uv pip compile` or
# `pip-compile` writes; its header command names the *.in inputs it was compiled from.
# An input holds bare exact pins only (no extras, no markers). Every input pin must
# equal the lock's one pin for that package, which carries no environment marker; every
# lock entry annotated `-r <input>` must still be pinned there (input paths are plain
# tokens, so the annotations match); and every tracked *.in file must be named by a lock
# header. Renovate's pip_requirements manager bumped the lock alone and left the
# input pin stale (pull requests 16 and 20, 2026-11-19); this gate turns that into a
# failing check offline, before the pull request reaches CI.
# The header must open the file, as Renovate's pip-compile manager also requires. A lock
# whose header follows a prelude (the Praetor-managed REUSE lock, compiled from an input
# this repository does not track) is named as not checked on every run.

import codecs
import os
import re
import shlex
import shutil
import subprocess
import sys
import threading
import time

MAX_FILE_BYTES = 4 * 1024 * 1024
MAX_HEADER_LINES = 16
MAX_TRACKED_PATHS = 100_000
MAX_LISTING_BYTES = 64 * 1024 * 1024
MAX_GIT_STDERR_BYTES = 64 * 1024
GIT_DEADLINE_SECONDS = 30
LOCK_MARKERS = (
    re.compile(r"^# This file was autogenerated by uv via the following command:$"),
    re.compile(r"^# This file is autogenerated by pip-compile with Python \S+$"),
)
COMMAND_LINE = re.compile(r"^# {4}(?P<command>\S+)(?P<arguments> .*)?$")
NAME = r"(?P<name>[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)"
VERSION = r"\s*==\s*(?P<version>[A-Za-z0-9][A-Za-z0-9.!+_-]*)\s*"
# A lock entry may carry extras and a non-empty environment marker, as uv writes them.
PIN = re.compile(rf"^{NAME}(?:\[[^\]]*\])?{VERSION}(?P<marker>;\s*\S.*)?$")
# An input line is a bare exact pin: the gate compares name and version only, so an
# extra or a marker it cannot compare is refused rather than passed unread.
INPUT_PIN = re.compile(rf"^{NAME}{VERSION}$")
# Input paths, in the header and in `-r` annotations, are one plain token: a quoted or
# whitespace-bearing path cannot be matched between the two reliably, so it fails closed.
PATH_TOKEN = r"[A-Za-z0-9._+/-]+"
INPUT_PATH = re.compile(rf"^{PATH_TOKEN}$")
VIA_FLAG = re.compile(r"(?:^|\s)-r(?:\s|$)")
VIA_INPUT = re.compile(rf"(?:^|\s)-r\s+(?P<source>{PATH_TOKEN})$")
INPUT_COMMENT = re.compile(r"(?:^|\s)#.*$")
# A public version in PEP 440 normal form without epoch or local segment
# (packaging.python.org/en/latest/specifications/version-specifiers/, "Normalization").
# Equivalent normal forms differ only in trailing zero release parts; any other
# spelling is refused in inputs rather than compared by a guess.
NUMBER = r"(?:0|[1-9]\d*)"
NORMAL_VERSION = re.compile(
    rf"^(?P<release>{NUMBER}(?:\.{NUMBER})*)"
    rf"(?P<suffix>(?:(?:a|b|rc){NUMBER})?(?:\.post{NUMBER})?(?:\.dev{NUMBER})?)$"
)
# Header options the gate accepts: flags that take no separate argument, and any
# --name=value option (Renovate's pip-compile manager also requires the = form).
# Anything else might consume the next word, so it fails closed. --no-annotate is
# absent: the stale-entry check reads the `-r <input>` annotations it removes.
BARE_FLAGS = frozenset(("--universal", "--generate-hashes", "--allow-unsafe", "--strip-extras",
                        "--no-emit-index-url", "--no-header"))
OPTION_WITH_VALUE = re.compile(r"^--[a-z][a-z0-9-]*=")


def canonical_name(name):
    """Return the PEP 503 normalised form of a distribution name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def canonical_version(version):
    """Return a PEP 440 normal-form version with trailing zero release parts dropped.

    Return None when version is not in normal form (for example 1.0RC1, v1.0, 1.0-post1).
    """
    match = NORMAL_VERSION.match(version)
    if not match:
        return None
    parts = match.group("release").split(".")
    for _ in range(len(parts) - 1):
        if parts[-1] != "0":
            break
        parts.pop()
    return ".".join(parts) + match.group("suffix")


def read_text(top, path):
    """Read tracked file path under top as UTF-8 text.

    Return (text, None) on success, or (None, error) if it is a symbolic link, resolves
    outside top, is missing, too large, opens with a byte order mark or is not UTF-8.
    """
    full = os.path.join(top, path)
    real_top = os.path.realpath(top)
    if os.path.islink(full) or os.path.commonpath((real_top, os.path.realpath(full))) != real_top:
        return None, f"{path}: is a symbolic link or resolves outside the checkout; this gate reads regular files only"
    try:
        size = os.path.getsize(full)
        if size > MAX_FILE_BYTES:
            return None, f"{path}: {size} bytes exceeds the {MAX_FILE_BYTES} byte limit"
        with open(full, "rb") as handle:
            data = handle.read(MAX_FILE_BYTES + 1)
    except OSError as error:
        return None, f"{path}: cannot read: {error}"
    if data.startswith(codecs.BOM_UTF8):
        return None, f"{path}: starts with a UTF-8 byte order mark, which uv and pip-compile never write"
    try:
        return data.decode("utf-8"), None
    except UnicodeDecodeError as error:
        return None, f"{path}: not UTF-8: {error}"


def lock_header(text):
    """Classify text by its lock header; return (kind, command).

    kind is "lock" when the leading comment block carries a uv or pip-compile marker
    (command is its compile line, or None if absent), "unchecked" when a marker appears
    anywhere else in the file, and None when text is no lock.
    """
    lines = text.splitlines()
    header = []
    for line in lines[:MAX_HEADER_LINES]:
        if not line.startswith("#"):
            break
        header.append(line)
    if not any(marker.match(line) for line in header for marker in LOCK_MARKERS):
        later = any(marker.match(line) for line in lines for marker in LOCK_MARKERS)
        return ("unchecked" if later else None), None
    for line in header:
        match = COMMAND_LINE.match(line)
        if match and match.group("command") in ("uv", "pip-compile"):
            return "lock", match.group("command") + (match.group("arguments") or "")
    return "lock", None


def command_inputs(path, command):
    """Split lock path's header command into (inputs, error), inputs relative to the repository top.

    Inputs and --output-file resolve against the lock's directory, where the header says to
    run the command; --output-file must name the lock itself.
    """
    if command is None:
        return None, f"{path}: lock header carries no compile command line"
    try:
        argv = shlex.split(command)
    except ValueError as error:
        return None, f"{path}: header command does not parse: {error}"
    if argv[:3] == ["uv", "pip", "compile"]:
        arguments = argv[3:]
    elif argv[:1] == ["pip-compile"]:
        arguments = argv[1:]
    else:
        return None, f"{path}: header command is neither uv pip compile nor pip-compile"
    base = os.path.dirname(path)
    inputs, output = [], None
    for argument in arguments:
        if argument.startswith("--output-file="):
            if output is not None:
                return None, f"{path}: header names --output-file more than once"
            output = os.path.normpath(os.path.join(base, argument.split("=", 1)[1]))
        elif not argument.startswith("-"):
            if not INPUT_PATH.match(argument):
                return None, f"{path}: header input {argument!r} is not a plain path of [A-Za-z0-9._+/-]"
            inputs.append(os.path.normpath(os.path.join(base, argument)))
        elif not (argument in BARE_FLAGS or OPTION_WITH_VALUE.match(argument)):
            return None, f"{path}: header option {argument} is not in this gate's allow-list"
    if output != os.path.normpath(path):
        return None, f"{path}: header --output-file names {output}, not this file"
    if not inputs:
        return None, f"{path}: header command names no input file"
    return inputs, None


def input_pins(path, text):
    """Parse the exact pins of input file path from text.

    Return ({name: (written pin, version)}, errors); any line other than a comment or a
    bare exact `name==version` pin is an error, so the gate never skips a requirement.
    """
    pins, errors = {}, []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = INPUT_COMMENT.sub("", raw).strip()
        if not line:
            continue
        match = INPUT_PIN.match(line)
        if not match:
            errors.append(f"{path}:{number}: not an exact name==version pin "
                          f"(extras and markers are refused): {raw.strip()}")
            continue
        name, version = canonical_name(match.group("name")), canonical_version(match.group("version"))
        if version is None:
            errors.append(f"{path}:{number}: version {match.group('version')} is not in PEP 440 "
                          "normal form; write it as the lock spells it")
            continue
        if name in pins:
            errors.append(f"{path}:{number}: {match.group('name')} is pinned twice")
            continue
        pins[name] = (f"{match.group('name')}=={match.group('version')}", version)
    return pins, errors


def annotation_source(path, number, comment):
    """Return (input, error) for indented lock comment, input being the `-r` path it names or None.

    An `-r` annotation must name one plain path; anything else (a quoted or whitespace-bearing
    path, or no path) is an error, since the stale-entry check could not match it to an input.
    """
    text = comment.lstrip("# ")
    if not VIA_FLAG.search(text):
        return None, None
    found = VIA_INPUT.search(text)
    if not found:
        return None, f"{path}:{number}: -r annotation does not name one plain path: {comment}"
    return os.path.normpath(found.group("source")), None


def lock_entries(path, text):
    """Parse lock path's text into ({name: {(version, marker): written}}, {name: inputs}, errors).

    Column-0 lines must be comments or pins; indented lines must be hashes or comments,
    whose `-r <input>` annotations (paths normalised, so ./requirements.in reads as
    requirements.in) record which inputs asked for the entry above them. marker is the
    entry's environment marker, or "" for an entry installed everywhere.
    """
    versions, via, errors, current = {}, {}, [], None
    for number, raw in enumerate(text.splitlines(), start=1):
        stripped = raw.strip()
        if not stripped or raw.startswith("#"):
            continue
        if raw[0].isspace():
            if stripped.startswith("#") and current:
                source, error = annotation_source(path, number, stripped)
                if error:
                    errors.append(error)
                elif source:
                    via.setdefault(current, set()).add(source)
            elif not (stripped.startswith("--hash=") or stripped.startswith("#")):
                errors.append(f"{path}:{number}: unexpected indented line: {stripped}")
            continue
        match = PIN.match(stripped.rstrip("\\").strip())
        if not match:
            errors.append(f"{path}:{number}: not a name==version lock entry: {stripped}")
            current = None
            continue
        current = canonical_name(match.group("name"))
        version, marker = match.group("version"), (match.group("marker") or ";")[1:].strip()
        # A version outside normal form keeps its spelling, so it can never equal an input pin;
        # a marked entry keeps its marker, so it can never satisfy an unconditional input pin.
        written = version + (f" ; {marker}" if marker else "")
        versions.setdefault(current, {})[(canonical_version(version) or version, marker)] = written
    return versions, via, errors


def compare_pair(lock, source, pins, versions, via, written):
    """Return drift errors between input source's pins and lock's entries.

    written is the input path as the header spells it, which `-r` annotations repeat. An
    input pin holds on every platform, so its lock entry must be one at that version with
    no environment marker; marked entries of other packages are not compared.
    """
    errors = []
    for name, (label, version) in sorted(pins.items()):
        locked = versions.get(name)
        if not locked:
            errors.append(f"{source}: {label} has no entry in {lock}")
        elif set(locked) != {(version, "")}:
            found = ", ".join(sorted(locked.values()))
            errors.append(f"{source}: {label} but {lock} pins {found}")
    for name, sources in sorted(via.items()):
        if written in sources and name not in pins:
            errors.append(f"{lock}: {name} is annotated -r {written}, but {source} no longer pins it")
    return errors


def check_lock(top, lock, text, tracked):
    """Check one lock against every input its header names.

    Return (inputs_covered, errors).
    """
    inputs, error = command_inputs(lock, lock_header(text)[1])
    if error:
        return [], [error]
    versions, via, errors = lock_entries(lock, text)
    base = os.path.dirname(lock)
    for source in inputs:
        if not source.endswith(".in"):
            errors.append(f"{lock}: input {source} is not a *.in file; this gate checks only *.in inputs")
            continue
        if source not in tracked:
            errors.append(f"{lock}: input {source} is not a tracked file")
            continue
        source_text, error = read_text(top, source)
        if error:
            errors.append(error)
            continue
        pins, pin_errors = input_pins(source, source_text)
        errors.extend(pin_errors)
        written = os.path.relpath(source, base or ".")
        errors.extend(compare_pair(lock, source, pins, versions, via, written))
    return inputs, errors


def read_bounded(process, limit, deadline):
    """Read the stdout and stderr pipes of process within deadline seconds and a byte cap.

    stdout is read to at most limit + 1 bytes and stderr to at most MAX_GIT_STDERR_BYTES,
    so memory stays bounded whatever the process writes. A watchdog kills the process at
    the deadline, and a stdout read past limit kills it at once; either kill ends the
    reads, since the git commands run here start no child that could hold the pipes open.
    A process that fills stderr before it closes stdout blocks until the watchdog fires,
    which fails closed. Return (stdout, stderr, returncode, problem), where problem is
    None, "limit" (stdout passed limit) or "deadline" (killed by the watchdog).
    """
    started = time.monotonic()
    watchdog = threading.Timer(deadline, process.kill)
    watchdog.start()
    try:
        stdout = process.stdout.read(limit + 1)
        overran = len(stdout) > limit
        if overran:
            process.kill()
        stderr = process.stderr.read(MAX_GIT_STDERR_BYTES)
        returncode = process.wait(timeout=deadline)
    finally:
        watchdog.cancel()
        process.stdout.close()
        process.stderr.close()
    if overran:
        return stdout[:limit], stderr, returncode, "limit"
    if returncode != 0 and time.monotonic() - started >= deadline:
        return stdout, stderr, returncode, "deadline"
    return stdout, stderr, returncode, None


def run_git(git, arguments, env, cwd=None):
    """Run the git binary at path git with the fixed argument list arguments (no shell).

    The argument list starts with the literal "git" and `executable` names the binary, so
    the program is the resolved path and no list element is a run-time program name.
    read_bounded caps the run at GIT_DEADLINE_SECONDS and stdout at MAX_LISTING_BYTES.
    Return (stdout bytes, None), or (None, error) if git cannot run, passes a cap or exits non-zero.
    """
    try:
        process = subprocess.Popen(["git", *arguments], executable=git, cwd=cwd, env=env,
                                   stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                   stderr=subprocess.PIPE)
        stdout, stderr, returncode, problem = read_bounded(process, MAX_LISTING_BYTES,
                                                           GIT_DEADLINE_SECONDS)
    except (OSError, subprocess.SubprocessError) as error:
        return None, f"git {arguments[0]} failed: {error}"
    if problem == "limit":
        return None, f"git {arguments[0]} wrote more than the {MAX_LISTING_BYTES} byte limit"
    if problem == "deadline":
        return None, f"git {arguments[0]} ran past the {GIT_DEADLINE_SECONDS} s deadline"
    if returncode != 0:
        detail = stderr.decode("utf-8", errors="replace").strip()
        return None, f"git {arguments[0]} failed (exit {returncode}): {detail}"
    return stdout, None


def git_environment(git):
    """Return (environment, None) without the variables that point git at another repository.

    `git rev-parse --local-env-vars` names them (GIT_DIR, GIT_WORK_TREE, GIT_INDEX_FILE and
    others), so git finds the repository from the working directory: the checkout this gate
    runs in. Return (None, error) if git cannot list them.
    """
    stdout, error = run_git(git, ["rev-parse", "--local-env-vars"], env=None)
    if error:
        return None, error
    local = set(os.fsdecode(stdout).split())
    return {key: value for key, value in os.environ.items() if key not in local}, None


def tracked_paths(git, top, env):
    """List tracked *.txt and *.in paths in top with git, run with environment env.

    Return (paths, None) on success, or (None, error) if git fails or its listing exceeds
    the byte or path limit.
    """
    stdout, error = run_git(git, ["ls-files", "-z", "--", "*.txt", "*.in"], env, cwd=top)
    if error:
        return None, error
    # run_git read at most MAX_LISTING_BYTES, which bounds the split below by a scalar.
    paths = [os.fsdecode(raw) for raw in stdout.split(b"\0") if raw]
    if len(paths) > MAX_TRACKED_PATHS:
        return None, f"git ls-files listed {len(paths)} paths, above the {MAX_TRACKED_PATHS} limit"
    return paths, None


def repository_top(git, env):
    """Return (top, None) for the checkout git finds with environment env, or (None, error)."""
    stdout, error = run_git(git, ["rev-parse", "--show-toplevel"], env)
    if error:
        return None, error
    return os.fsdecode(stdout.strip()), None


def check_repository(top, paths):
    """Check every tracked lock in top and every tracked input.

    Return (checked, unchecked, errors): lock paths checked, lock paths whose header
    follows a prelude, and drift or parse errors.
    """
    tracked, covered, checked, unchecked, errors = set(paths), set(), [], [], []
    for path in sorted(p for p in paths if p.endswith(".txt")):
        text, error = read_text(top, path)
        if error:
            errors.append(error)
            continue
        kind, _ = lock_header(text)
        if kind == "unchecked":
            unchecked.append(path)
        if kind != "lock":
            continue
        checked.append(path)
        inputs, lock_errors = check_lock(top, path, text, tracked)
        covered.update(inputs)
        errors.extend(lock_errors)
    for path in sorted(p for p in paths if p.endswith(".in")):
        if path not in covered:
            errors.append(f"{path}: no tracked lock names this input in its header")
    return checked, unchecked, errors


def main():
    """Check this checkout's compiled requirements locks against their inputs.

    Print drift to stderr and return 1, or print a summary and return 0 when all agree.
    """
    git = shutil.which("git")
    if git is None:
        print("requirements_lock_gate: git not found on PATH", file=sys.stderr)
        return 1
    top = paths = None
    env, error = git_environment(git)
    if error is None:
        top, error = repository_top(git, env)
    if error is None:
        paths, error = tracked_paths(git, top, env)
    if error:
        print(f"requirements_lock_gate: {error}", file=sys.stderr)
        return 1
    checked, unchecked, errors = check_repository(top, paths)
    for path in unchecked:
        print(f"requirements_lock_gate: not checked: {path}: lock header does not open the file")
    for line in errors:
        print(f"requirements_lock_gate: {line}", file=sys.stderr)
    if errors:
        print(
            "requirements_lock_gate: change the pin in the input, then regenerate the lock "
            "with the command in its header",
            file=sys.stderr,
        )
        return 1
    print(f"requirements_lock_gate: pins agree with their inputs: {', '.join(checked) or 'no locks'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
